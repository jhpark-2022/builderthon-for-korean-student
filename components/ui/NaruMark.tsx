// 나루 점. 흰 링 하나와 그 안의 주황 점 하나.
//
// 기하는 public/naru/naru-symbol.svg에서 그대로 가져왔습니다. 원본은
// 360×360 캔버스에 배 모양 path가 있고, 그 뱃머리 끝에 원 두 개가 겹쳐
// 있습니다: r=13 흰 원 위에 r=8 주황 원. 여기서는 그 두 원만 떼어내
// 26×26으로 정규화했습니다.
//
//   <circle r="13" fill="#FFFFFF" />   바깥 링
//   <circle r="8"  fill="#EE8A4F" />   안쪽 점  (지름의 61.5%)
//
// 눈대중으로 다시 그리지 마세요. 로고 가이드가 비율 변경·색 변경·회전·그림자를
// 금지합니다(public/naru/README.md). 무게를 조절해야 하면 크기만 바꾸세요.
//
// ── 어디에 쓰는가 ────────────────────────────────────────────────────────────
// 나루 홈의 #why, 코어 두 장의 번호 자리. **그 두 곳뿐입니다.**
//
// 이 표식이 거기 있는 이유는 세 가지입니다.
//
//  1. 링과 점은 면이 아니라 점입니다. 이 사이트의 지배 규칙("주황은 점이지
//     면이 아니다")을 구조적으로 어길 수 없는 유일한 주황 사용법이에요.
//  2. 배경이 이미 같은 말을 하고 있습니다. 깊은 물 층이 링과 점을 그리고
//     스크롤을 따라 내려옵니다(lib/background/shaders/water.ts). 머리의 로고,
//     물속의 점, 그리고 여기. 페이지에서 같은 것을 세 번 말하는 유일한 형태입니다.
//  3. 코어가 정확히 둘이고 표식은 점 하나입니다. 점 두 개가 "두 가지"로
//     읽히고, 그게 바로 그 위 h2의 문장입니다.
//
// 목록 불릿으로 쓰지 마세요. 사진 위에 얹지 마세요(가이드가 금지합니다).
// 18px 아래로 내리지 마세요 - 링이 지름의 5/26이라 18px에서 3.5px이고, 그
// 아래로는 1× 화면에서 흐린 후광으로 뭉갭니다.
//
// aria-hidden인 이유: 이 표식이 나르는 뜻은 옆의 01/02가 글자로 이미 말합니다.
// 보조기술에 같은 것을 두 번 줄 이유가 없어요.
// ─────────────────────────────────────────────────────────────────────────────
export default function NaruMark({ className = "" }: { className?: string }) {
  return (
    <svg
      viewBox="0 0 26 26"
      aria-hidden
      focusable="false"
      className={`shrink-0 ${className}`}
    >
      <circle cx="13" cy="13" r="13" fill="#FFFFFF" />
      <circle cx="13" cy="13" r="8" fill="#EE8A4F" />
    </svg>
  );
}
